/**
 * Кружок цвета для фильтра и карточки товара. В админке цвет — свободный текст,
 * поэтому ищем сначала точное название, потом по первому слову
 * («Изумрудный / золото» → изумрудный, «Комбинированный желтый» → комбинированный).
 * Неизвестный цвет — null, такой выводится одной подписью без кружка.
 */

const MULTI = "conic-gradient(#e63946, #f4d03f, #2e8b57, #1f4e9c, #7b3fa0, #e63946)";

const COLORS: Record<string, string> = {
  бежевый: "#d8c3a5",
  "светло-бежевый": "#eadbc8",
  белый: "#ffffff",
  молочный: "#f5f0e1",
  кремовый: "#f3e5c0",
  песочный: "#d9b98a",
  желтый: "#f4d03f",
  оранжевый: "#f28c28",
  терракотовый: "#c8654a",
  кирпичный: "#b5523b",
  красный: "#d62828",
  розовый: "#f4a6c0",
  сиреневый: "#c8a2c8",
  фиолетовый: "#7b3fa0",
  голубой: "#8ecae6",
  синий: "#1f4e9c",
  "темно-синий": "#1b2a4a",
  мятный: "#98e2c6",
  салатовый: "#a6d96a",
  "светло-зеленый": "#9ad29a",
  зеленый: "#2e8b57",
  изумрудный: "#0f7b5f",
  оливковый: "#808000",
  хаки: "#8a865d",
  коричневый: "#7b4a2d",
  серый: "#9e9e9e",
  черный: "#111111",
  комбинированный: MULTI,
  разноцветный: MULTI,
};

export function colorSwatch(name: string): string | null {
  const key = name.trim().toLowerCase().replace(/ё/g, "е");
  if (COLORS[key]) return COLORS[key];
  const first = key.split(/[\s/,]+/)[0];
  return COLORS[first] ?? null;
}

/** Белый и молочный на белом фоне теряются — им нужна обводка. */
export function isLightSwatch(css: string | null): boolean {
  return css === "#ffffff" || css === "#f5f0e1" || css === "#f3e5c0";
}
