/**
 * Базовый адрес бэкенда для запросов ДАННЫХ.
 *
 * В браузере это публичный домен: другого пути к бэкенду у него нет.
 *
 * На сервере — наоборот, публичный домен использовать нельзя. Запрос из
 * контейнера ушёл бы в Cloudflare и вернулся петлёй на эту же машину, так что
 * любая заминка на участке Cloudflare↔сервер ломала рендер страниц, хотя
 * бэкенд стоит в соседнем контейнере. 18.08.2026 фронт из-за этого получил
 * 525 от собственного бэкенда (см. docs/server-side-api-direct.md).
 * Поэтому на сервере идём напрямую в контейнер, минуя интернет и nginx.
 *
 * Только для fetch. Ссылки и src картинок, которые уедут в браузер, строятся
 * от NEXT_PUBLIC_API_URL и через эту функцию проходить не должны.
 */
export function apiBase(): string {
  if (typeof window === "undefined") {
    return (
      process.env.INTERNAL_API_URL ||
      process.env.NEXT_PUBLIC_API_URL ||
      ""
    );
  }

  return process.env.NEXT_PUBLIC_API_URL || "";
}
